-- Admin: set the selected driver's five stock values.
create or replace function public.admin_set_driver_stock(
  p_driver_id uuid,
  p_stock jsonb,
  p_reason text
) returns void
language plpgsql
security definer
set search_path=public
as $$
declare
  i integer;
  v_stock numeric;
  names text[] := array['Large product','Ketnet','3Motion','NEP','Median'];
  prices numeric[] := array[50,15,15,15,35];
  types text[] := array['fractional_large','standard','standard','standard','standard'];
begin
  if not public.is_sales_admin() then raise exception 'Admin access required'; end if;
  if length(trim(coalesce(p_reason,'')))=0 then raise exception 'Adjustment reason is required'; end if;
  if not exists(select 1 from public.profiles where user_id=p_driver_id) then raise exception 'Driver not found'; end if;

  for i in 1..5 loop
    v_stock:=greatest(coalesce((p_stock->>i::text)::numeric,0),0);
    insert into public.products(
      user_id,slot,name,price,product_type,stock,standard_amount,full_price,
      deal_type,deal_qty,deal_price,free_qty,updated_at
    ) values(
      p_driver_id,i,names[i],prices[i],types[i],v_stock,
      case when i=1 then 0.7 else 1 end,
      case when i=1 then 60 else 0 end,
      'none',0,0,0,now()
    )
    on conflict(user_id,slot) do update set
      name=excluded.name, price=excluded.price, product_type=excluded.product_type,
      stock=excluded.stock, standard_amount=excluded.standard_amount,
      full_price=excluded.full_price, updated_at=now();
  end loop;
end;
$$;
grant execute on function public.admin_set_driver_stock(uuid,jsonb,text) to authenticated;

-- Admin: approve/decline one extra-pay request for the selected driver.
create or replace function public.admin_review_supplement(
  p_driver_id uuid,
  p_sale_id uuid,
  p_status text
) returns void
language plpgsql
security definer
set search_path=public
as $$
begin
  if not public.is_sales_admin() then raise exception 'Admin access required'; end if;
  if p_status not in ('approved','declined') then raise exception 'Invalid status'; end if;

  update public.sales
  set supplement_status=p_status,
      supplement_reviewed_at=now(),
      supplement_reviewed_by=auth.uid()
  where id=p_sale_id
    and user_id=p_driver_id
    and supplement_amount>0
    and supplement_status='pending';

  if not found then raise exception 'Pending supplement request not found'; end if;
end;
$$;
grant execute on function public.admin_review_supplement(uuid,uuid,text) to authenticated;

