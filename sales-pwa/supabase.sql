-- Record a sale and deduct fractional inventory in one database transaction.
create or replace function public.record_sale_with_stock(
  p_sale_id uuid,
  p_sold_at timestamptz,
  p_total numeric,
  p_note text,
  p_items jsonb
) returns void
language plpgsql
security invoker
set search_path = public
as $$
declare
  item jsonb;
  v_slot integer;
  v_used numeric;
begin
  for item in select value from jsonb_array_elements(p_items)
  loop
    v_slot := coalesce((item->>'id')::integer, 0);
    v_used := coalesce((item->>'stockUsed')::numeric, 0);

    if v_used > 0 then
      update public.products
      set stock = stock - v_used,
          updated_at = now()
      where user_id = auth.uid()
        and slot = v_slot
        and stock >= v_used;

      if not found then
        raise exception 'Insufficient stock for product slot %', v_slot;
      end if;
    end if;
  end loop;

  insert into public.sales(id,user_id,sold_at,total,note,items)
  values(p_sale_id,auth.uid(),p_sold_at,p_total,coalesce(p_note,''),p_items);
end;
$$;

-- Deleting a sale restores the exact stock amount that sale consumed.
create or replace function public.delete_sale_restore_stock(p_sale_id uuid)
returns void
language plpgsql
security invoker
set search_path = public
as $$
declare
  sale_items jsonb;
  item jsonb;
  v_slot integer;
  v_used numeric;
begin
  select items into sale_items
  from public.sales
  where id = p_sale_id and user_id = auth.uid()
  for update;

  if sale_items is null then
    raise exception 'Sale not found';
  end if;

  for item in select value from jsonb_array_elements(sale_items)
  loop
    v_slot := coalesce((item->>'id')::integer, 0);
    v_used := coalesce((item->>'stockUsed')::numeric, 0);
    if v_used > 0 then
      update public.products
      set stock = stock + v_used,
          updated_at = now()
      where user_id = auth.uid() and slot = v_slot;
    end if;
  end loop;

  delete from public.sales where id = p_sale_id and user_id = auth.uid();
end;
$$;

grant execute on function public.record_sale_with_stock(uuid,timestamptz,numeric,text,jsonb) to authenticated;
grant execute on function public.delete_sale_restore_stock(uuid) to authenticated;

