-- Sales Log database setup + inventory upgrade.
-- Safe to run again in Supabase -> SQL Editor.

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  slot integer not null check (slot between 1 and 5),
  name text not null,
  price numeric(12,2) not null default 0,
  deal_type text not null default 'none' check (deal_type in ('none','bundle','free')),
  deal_qty integer not null default 0,
  deal_price numeric(12,2) not null default 0,
  free_qty integer not null default 0,
  updated_at timestamptz not null default now(),
  unique(user_id, slot)
);

-- Inventory/product-type fields added by v3.
alter table public.products add column if not exists product_type text not null default 'standard';
alter table public.products add column if not exists stock numeric(12,3) not null default 0;
alter table public.products add column if not exists standard_amount numeric(12,3) not null default 1;
alter table public.products add column if not exists full_price numeric(12,2) not null default 0;

create table if not exists public.sales (
  id uuid primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  sold_at timestamptz not null default now(),
  total numeric(12,2) not null default 0,
  note text not null default '',
  items jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now()
);

alter table public.products enable row level security;
alter table public.sales enable row level security;

