create table if not exists public.products (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  slot integer not null check (slot between 1 and 5),
  name text not null,
  price numeric(12,2) not null default 0,
  deal_type text not null default 'none',
  deal_qty integer not null default 0,
  deal_price numeric(12,2) not null default 0,
  free_qty integer not null default 0,
  product_type text not null default 'standard',
  stock numeric(12,3) not null default 0,
  standard_amount numeric(12,3) not null default 1,
  full_price numeric(12,2) not null default 0,
  updated_at timestamptz not null default now(),
  unique(user_id,slot)
);

create table if not exists public.sales (
  id uuid primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  sold_at timestamptz not null default now(),
  total numeric(12,2) not null default 0,
  note text not null default '',
  items jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now()
);

