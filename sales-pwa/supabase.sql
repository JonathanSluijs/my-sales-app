-- Admin: list every non-admin account as a driver.
create or replace function public.admin_list_drivers()
returns table(user_id uuid,email text,display_name text)
language sql
stable
security definer
set search_path=public
as $$
  select p.user_id,p.email,p.display_name
  from public.profiles p
  where public.is_sales_admin()
    and not exists(select 1 from public.admin_emails a where lower(a.email)=lower(p.email))
  order by coalesce(nullif(p.display_name,''),p.email);
$$;
grant execute on function public.admin_list_drivers() to authenticated;

