-- Driver sale: stock is deducted only from the signed-in driver's own inventory.
create or replace function public.record_sale_with_stock(
  p_sale_id uuid,
  p_sold_at timestamptz,
  p_total numeric,
  p_note text,
  p_items jsonb,
  p_supplement_amount numeric default 0,
  p_supplement_note text default ''
) returns void
language plpgsql
security invoker
set search_path=public
as $$
declare
  item jsonb;
  v_slot integer;
  v_used numeric;
  v_supp numeric := greatest(coalesce(p_supplement_amount,0),0);
begin
  if v_supp > 0 and length(trim(coalesce(p_supplement_note,'')))=0 then
    raise exception 'Supplement reason is required';
  end if;

  for item in select value from jsonb_array_elements(p_items)
  loop
    v_slot:=coalesce((item->>'id')::integer,0);
    v_used:=coalesce((item->>'stockUsed')::numeric,0);
    if v_used>0 then
      update public.products
      set stock=stock-v_used, updated_at=now()
      where user_id=auth.uid() and slot=v_slot and stock>=v_used;
      if not found then raise exception 'Insufficient stock for product slot %',v_slot; end if;
    end if;
  end loop;

  insert into public.sales(
    id,user_id,sold_at,total,note,items,
    supplement_amount,supplement_note,supplement_status
  ) values(
    p_sale_id,auth.uid(),p_sold_at,p_total,coalesce(p_note,''),p_items,
    v_supp,coalesce(p_supplement_note,''),
    case when v_supp>0 then 'pending' else 'none' end
  );
end;
$$;
grant execute on function public.record_sale_with_stock(uuid,timestamptz,numeric,text,jsonb,numeric,text) to authenticated;

